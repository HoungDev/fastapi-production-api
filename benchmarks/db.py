"""Controlled PostgreSQL benchmark for the sync path and an async prototype.

The benchmark owns only the ``fastapi_benchmark`` schema. It deliberately does
not import the FastAPI application or replace its synchronous database path.
"""

from __future__ import annotations

import argparse
import asyncio
import json
import os
import platform
import statistics
import sys
import threading
from concurrent.futures import ThreadPoolExecutor, as_completed
from dataclasses import asdict, dataclass
from datetime import UTC, datetime
from pathlib import Path
from time import perf_counter
from typing import Any, Literal

from sqlalchemy import create_engine, event, make_url, text
from sqlalchemy.engine import URL, Engine
from sqlalchemy.ext.asyncio import AsyncEngine, create_async_engine

SCHEMA = "fastapi_benchmark"
SCHEMA_VERSION = 1
SCENARIOS = (
    "authenticated_read",
    "session_list",
    "refresh_rotation",
    "write",
    "mixed",
)
Mode = Literal["sync", "async"]


class BenchmarkSafetyError(ValueError):
    """Raised when a URL is not clearly an isolated local/test database."""


class RollbackProbe(RuntimeError):
    """Internal sentinel used to force an async transaction rollback."""


@dataclass(frozen=True)
class RunConfig:
    iterations: int
    warmup: int
    concurrency: int
    pool_size: int
    max_overflow: int


@dataclass(frozen=True)
class Sample:
    latency_ms: float
    pool_wait_ms: float
    error: str | None = None


class PoolObserver:
    """Collect bounded pool activity without logging connection details."""

    def __init__(self) -> None:
        self._lock = threading.Lock()
        self.checkouts = 0
        self.checkins = 0
        self.in_use = 0
        self.peak_in_use = 0

    def checkout(self, *_: Any) -> None:
        with self._lock:
            self.checkouts += 1
            self.in_use += 1
            self.peak_in_use = max(self.peak_in_use, self.in_use)

    def checkin(self, *_: Any) -> None:
        with self._lock:
            self.checkins += 1
            self.in_use = max(0, self.in_use - 1)

    def snapshot(self) -> dict[str, int]:
        with self._lock:
            return {
                "checkouts": self.checkouts,
                "checkins": self.checkins,
                "peak_in_use": self.peak_in_use,
            }

    def reset(self) -> None:
        with self._lock:
            self.checkouts = 0
            self.checkins = 0
            self.in_use = 0
            self.peak_in_use = 0


def validate_benchmark_url(value: str) -> URL:
    """Fail closed unless the target is an obvious local PostgreSQL test DB."""
    url = make_url(value)
    if url.get_backend_name() != "postgresql":
        raise BenchmarkSafetyError("Benchmarking requires PostgreSQL.")

    host = (url.host or "").lower()
    if host not in {"localhost", "127.0.0.1", "::1", "postgres"}:
        raise BenchmarkSafetyError(
            "Refusing a non-local database host; use an isolated local/CI database."
        )

    database = (url.database or "").lower()
    if not any(marker in database for marker in ("test", "bench", "local", "dev")):
        raise BenchmarkSafetyError(
            "Database name must contain test, bench, local, or dev."
        )
    return url


def sync_url(value: str) -> URL:
    return validate_benchmark_url(value).set(drivername="postgresql+psycopg")


def async_url(value: str) -> URL:
    return validate_benchmark_url(value).set(drivername="postgresql+asyncpg")


def _engine(value: str, *, pool_size: int = 5, max_overflow: int = 0) -> Engine:
    return create_engine(
        sync_url(value),
        pool_pre_ping=True,
        pool_size=pool_size,
        max_overflow=max_overflow,
        pool_timeout=10,
    )


def _async_engine(
    value: str, *, pool_size: int = 5, max_overflow: int = 0
) -> AsyncEngine:
    return create_async_engine(
        async_url(value),
        pool_pre_ping=True,
        pool_size=pool_size,
        max_overflow=max_overflow,
        pool_timeout=10,
    )


def prepare_fixture(database_url: str, records: int) -> None:
    if records < 10:
        raise ValueError("records must be at least 10")
    engine = _engine(database_url)
    try:
        with engine.begin() as connection:
            connection.execute(text(f"CREATE SCHEMA IF NOT EXISTS {SCHEMA}"))
            connection.execute(
                text(
                    f"""
                    CREATE TABLE IF NOT EXISTS {SCHEMA}.principals (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        username VARCHAR(80) NOT NULL UNIQUE,
                        role VARCHAR(20) NOT NULL,
                        rotation_counter BIGINT NOT NULL DEFAULT 0,
                        payload TEXT NOT NULL
                    )
                    """
                )
            )
            connection.execute(
                text(
                    f"""
                    CREATE TABLE IF NOT EXISTS {SCHEMA}.sessions (
                        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                        principal_id BIGINT NOT NULL REFERENCES
                            {SCHEMA}.principals(id) ON DELETE CASCADE,
                        created_at TIMESTAMPTZ NOT NULL,
                        revoked_at TIMESTAMPTZ NULL
                    )
                    """
                )
            )
            connection.execute(
                text(
                    f"CREATE INDEX IF NOT EXISTS ix_benchmark_sessions_principal "
                    f"ON {SCHEMA}.sessions (principal_id, created_at DESC)"
                )
            )
            connection.execute(
                text(
                    f"TRUNCATE {SCHEMA}.sessions, {SCHEMA}.principals RESTART IDENTITY"
                )
            )
            principals = [
                {
                    "username": f"benchmark-user-{index:06d}",
                    "role": "admin" if index % 20 == 0 else "user",
                    "payload": "x" * 256,
                }
                for index in range(records)
            ]
            connection.execute(
                text(
                    f"INSERT INTO {SCHEMA}.principals (username, role, payload) "
                    "VALUES (:username, :role, :payload)"
                ),
                principals,
            )
            connection.execute(
                text(
                    f"""
                    INSERT INTO {SCHEMA}.sessions (principal_id, created_at)
                    SELECT principal.id, NOW() - (n * INTERVAL '1 minute')
                    FROM {SCHEMA}.principals AS principal
                    CROSS JOIN generate_series(1, 3) AS n
                    """
                )
            )
            connection.execute(text(f"ANALYZE {SCHEMA}.principals"))
            connection.execute(text(f"ANALYZE {SCHEMA}.sessions"))
    finally:
        engine.dispose()


def cleanup_fixture(database_url: str) -> None:
    engine = _engine(database_url)
    try:
        with engine.begin() as connection:
            connection.execute(text(f"DROP SCHEMA IF EXISTS {SCHEMA} CASCADE"))
    finally:
        engine.dispose()


def _scenario_for(scenario: str, index: int) -> str:
    if scenario != "mixed":
        return scenario
    return ("authenticated_read", "session_list", "refresh_rotation", "write")[
        index % 4
    ]


def _statements(scenario: str, index: int) -> list[tuple[str, dict[str, Any]]]:
    scenario = _scenario_for(scenario, index)
    record_id = (index % 10) + 1
    username = f"benchmark-user-{index % 10:06d}"
    if scenario == "authenticated_read":
        return [
            (
                f"SELECT id, role, payload FROM {SCHEMA}.principals "
                "WHERE username = :username",
                {"username": username},
            )
        ]
    if scenario == "session_list":
        return [
            (
                f"SELECT id, created_at FROM {SCHEMA}.sessions "
                "WHERE principal_id = :record_id AND revoked_at IS NULL "
                "ORDER BY created_at DESC LIMIT 20",
                {"record_id": record_id},
            )
        ]
    if scenario == "refresh_rotation":
        return [
            (
                f"SELECT rotation_counter FROM {SCHEMA}.principals "
                "WHERE id = :record_id FOR UPDATE",
                {"record_id": record_id},
            ),
            (
                f"UPDATE {SCHEMA}.principals SET rotation_counter = "
                "rotation_counter + 1 WHERE id = :record_id",
                {"record_id": record_id},
            ),
        ]
    if scenario == "write":
        return [
            (
                f"UPDATE {SCHEMA}.principals SET payload = payload "
                "WHERE id = :record_id",
                {"record_id": record_id},
            )
        ]
    raise ValueError(f"Unknown scenario: {scenario}")


def _attach_observer(engine: Engine, observer: PoolObserver) -> None:
    event.listen(engine, "checkout", observer.checkout)
    event.listen(engine, "checkin", observer.checkin)


def _sync_sample(engine: Engine, scenario: str, index: int) -> Sample:
    started = perf_counter()
    try:
        acquire_started = perf_counter()
        with engine.begin() as connection:
            acquired = perf_counter()
            for statement, params in _statements(scenario, index):
                connection.execute(text(statement), params)
        finished = perf_counter()
        return Sample(
            latency_ms=(finished - started) * 1000,
            pool_wait_ms=(acquired - acquire_started) * 1000,
        )
    except Exception as error:  # benchmark errors belong in the result artifact
        return Sample(
            latency_ms=(perf_counter() - started) * 1000,
            pool_wait_ms=0,
            error=type(error).__name__,
        )


async def _async_sample(engine: AsyncEngine, scenario: str, index: int) -> Sample:
    started = perf_counter()
    try:
        acquire_started = perf_counter()
        async with engine.begin() as connection:
            acquired = perf_counter()
            for statement, params in _statements(scenario, index):
                await connection.execute(text(statement), params)
        finished = perf_counter()
        return Sample(
            latency_ms=(finished - started) * 1000,
            pool_wait_ms=(acquired - acquire_started) * 1000,
        )
    except Exception as error:  # benchmark errors belong in the result artifact
        return Sample(
            latency_ms=(perf_counter() - started) * 1000,
            pool_wait_ms=0,
            error=type(error).__name__,
        )


def _percentile(values: list[float], percentile: float) -> float:
    if not values:
        return 0.0
    ordered = sorted(values)
    position = (len(ordered) - 1) * percentile
    lower = int(position)
    upper = min(lower + 1, len(ordered) - 1)
    weight = position - lower
    return ordered[lower] * (1 - weight) + ordered[upper] * weight


def summarize(
    *,
    mode: Mode,
    scenario: str,
    samples: list[Sample],
    duration: float,
    observer: PoolObserver,
) -> dict[str, Any]:
    successful = [sample for sample in samples if sample.error is None]
    latencies = [sample.latency_ms for sample in successful]
    waits = [sample.pool_wait_ms for sample in successful]
    error_types: dict[str, int] = {}
    for sample in samples:
        if sample.error:
            error_types[sample.error] = error_types.get(sample.error, 0) + 1

    def distribution(values: list[float]) -> dict[str, float]:
        return {
            "minimum": round(min(values, default=0), 3),
            "median": round(statistics.median(values) if values else 0, 3),
            "p95": round(_percentile(values, 0.95), 3),
            "p99": round(_percentile(values, 0.99), 3),
            "maximum": round(max(values, default=0), 3),
        }

    return {
        "mode": mode,
        "scenario": scenario,
        "attempts": len(samples),
        "successes": len(successful),
        "errors": len(samples) - len(successful),
        "error_rate": round((len(samples) - len(successful)) / len(samples), 6)
        if samples
        else 0,
        "error_types": error_types,
        "duration_seconds": round(duration, 6),
        "throughput_rps": round(len(successful) / duration, 3) if duration else 0,
        "latency_ms": distribution(latencies),
        "pool_wait_ms": distribution(waits),
        "pool": observer.snapshot(),
    }


def run_sync(database_url: str, scenario: str, config: RunConfig) -> dict[str, Any]:
    engine = _engine(
        database_url,
        pool_size=config.pool_size,
        max_overflow=config.max_overflow,
    )
    observer = PoolObserver()
    _attach_observer(engine, observer)
    try:
        for index in range(config.warmup):
            _sync_sample(engine, scenario, index)
        observer.reset()
        started = perf_counter()
        with ThreadPoolExecutor(max_workers=config.concurrency) as executor:
            futures = [
                executor.submit(_sync_sample, engine, scenario, index)
                for index in range(config.iterations)
            ]
            samples = [future.result() for future in as_completed(futures)]
        duration = perf_counter() - started
        return summarize(
            mode="sync",
            scenario=scenario,
            samples=samples,
            duration=duration,
            observer=observer,
        )
    finally:
        engine.dispose()


async def run_async(
    database_url: str, scenario: str, config: RunConfig
) -> dict[str, Any]:
    engine = _async_engine(
        database_url,
        pool_size=config.pool_size,
        max_overflow=config.max_overflow,
    )
    observer = PoolObserver()
    _attach_observer(engine.sync_engine, observer)
    semaphore = asyncio.Semaphore(config.concurrency)

    async def bounded(index: int) -> Sample:
        async with semaphore:
            return await _async_sample(engine, scenario, index)

    try:
        for index in range(config.warmup):
            await bounded(index)
        observer.reset()
        started = perf_counter()
        samples = await asyncio.gather(
            *(bounded(index) for index in range(config.iterations))
        )
        duration = perf_counter() - started
        return summarize(
            mode="async",
            scenario=scenario,
            samples=samples,
            duration=duration,
            observer=observer,
        )
    finally:
        await engine.dispose()


async def verify_async_rollback(database_url: str) -> bool:
    """Verify that the isolated async prototype preserves rollback semantics."""
    engine = _async_engine(database_url, pool_size=1)
    try:
        async with engine.connect() as connection:
            before = await connection.scalar(
                text(f"SELECT rotation_counter FROM {SCHEMA}.principals WHERE id = 1")
            )
        try:
            async with engine.begin() as connection:
                await connection.execute(
                    text(
                        f"UPDATE {SCHEMA}.principals SET rotation_counter = "
                        "rotation_counter + 1 WHERE id = 1"
                    )
                )
                raise RollbackProbe("force rollback")
        except RollbackProbe:
            pass
        async with engine.connect() as connection:
            after = await connection.scalar(
                text(f"SELECT rotation_counter FROM {SCHEMA}.principals WHERE id = 1")
            )
        return before == after
    finally:
        await engine.dispose()


def build_report(
    database_url: str,
    modes: list[Mode],
    scenarios: list[str],
    config: RunConfig,
) -> dict[str, Any]:
    validated = validate_benchmark_url(database_url)
    results = []
    for scenario in scenarios:
        if "sync" in modes:
            results.append(run_sync(database_url, scenario, config))
        if "async" in modes:
            results.append(asyncio.run(run_async(database_url, scenario, config)))
    return {
        "schema_version": SCHEMA_VERSION,
        "generated_at": datetime.now(UTC).isoformat(),
        "environment": {
            "python": platform.python_version(),
            "platform": platform.platform(),
            "database_host": validated.host,
            "database_name": validated.database,
        },
        "config": asdict(config),
        "results": results,
    }


def _database_url(args: argparse.Namespace) -> str:
    value = args.database_url or os.environ.get("BENCHMARK_DATABASE_URL")
    if not value:
        raise BenchmarkSafetyError(
            "Set BENCHMARK_DATABASE_URL or pass --database-url; DATABASE_URL is "
            "intentionally not used implicitly."
        )
    validate_benchmark_url(value)
    return value


def _add_database_argument(parser: argparse.ArgumentParser) -> None:
    parser.add_argument(
        "--database-url",
        help="Isolated local/CI PostgreSQL URL (or set BENCHMARK_DATABASE_URL).",
    )


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    subparsers = parser.add_subparsers(dest="command", required=True)

    prepare = subparsers.add_parser("prepare", help="Create deterministic fixtures.")
    _add_database_argument(prepare)
    prepare.add_argument("--records", type=int, default=1_000)

    cleanup = subparsers.add_parser("cleanup", help="Drop only the benchmark schema.")
    _add_database_argument(cleanup)

    rollback = subparsers.add_parser(
        "verify-async-rollback", help="Check async transaction rollback semantics."
    )
    _add_database_argument(rollback)

    run = subparsers.add_parser("run", help="Run controlled sync/async comparisons.")
    _add_database_argument(run)
    run.add_argument("--mode", choices=("sync", "async", "both"), default="both")
    run.add_argument(
        "--scenarios", nargs="+", choices=SCENARIOS, default=list(SCENARIOS)
    )
    run.add_argument("--iterations", type=int, default=1_000)
    run.add_argument("--warmup", type=int, default=100)
    run.add_argument("--concurrency", type=int, default=10)
    run.add_argument("--pool-size", type=int, default=5)
    run.add_argument("--max-overflow", type=int, default=0)
    run.add_argument("--output", type=Path, default=Path("benchmark-results.json"))
    return parser


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    try:
        database_url = _database_url(args)
        if args.command == "prepare":
            prepare_fixture(database_url, args.records)
            return 0
        if args.command == "cleanup":
            cleanup_fixture(database_url)
            return 0
        if args.command == "verify-async-rollback":
            if not asyncio.run(verify_async_rollback(database_url)):
                print("Async rollback probe failed.", file=sys.stderr)
                return 1
            print("Async rollback probe passed.")
            return 0

        values = (
            args.iterations,
            args.concurrency,
            args.pool_size,
        )
        if (
            any(value < 1 for value in values)
            or args.warmup < 0
            or args.max_overflow < 0
        ):
            raise ValueError("iterations/concurrency/pool-size must be positive")
        modes: list[Mode] = ["sync", "async"] if args.mode == "both" else [args.mode]
        report = build_report(
            database_url,
            modes,
            args.scenarios,
            RunConfig(
                iterations=args.iterations,
                warmup=args.warmup,
                concurrency=args.concurrency,
                pool_size=args.pool_size,
                max_overflow=args.max_overflow,
            ),
        )
        args.output.parent.mkdir(parents=True, exist_ok=True)
        args.output.write_text(json.dumps(report, indent=2) + "\n", encoding="utf-8")
        print(json.dumps(report, indent=2))
        return 1 if any(result["errors"] for result in report["results"]) else 0
    except (BenchmarkSafetyError, ValueError) as error:
        print(f"Error: {error}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
